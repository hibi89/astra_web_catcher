from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator, model_validator


class ClosedModel(BaseModel):
    model_config = ConfigDict(extra='forbid')


class SyntheticRow(ClosedModel):
    id: str = Field(pattern=r'^[a-z][a-z0-9_-]{0,39}$')
    title: str = Field(min_length=1, max_length=100)
    category: str = Field(min_length=1, max_length=60)
    score: int = Field(ge=0, le=10000, strict=True)


class SyntheticDemo(ClosedModel):
    schema_version: Literal['0.1']
    source_kind: Literal['synthetic_fixture']
    run_mode: Literal['temporary_demo_only']
    title: str = Field(min_length=1, max_length=100)
    items: list[SyntheticRow] = Field(min_length=1, max_length=100)

    @model_validator(mode='after')
    def unique_ids(self):
        ids = [x.id for x in self.items]
        if len(ids) != len(set(ids)):
            raise ValueError('duplicate demo row IDs')
        return self


